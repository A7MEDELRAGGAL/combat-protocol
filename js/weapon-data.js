export function weaponById(id) {
  return WEAPON_DEFS.find((weapon) => weapon.id === id) ?? null;
}

export function shotsPerSecond(weapon) {
  return (weapon.rpm ?? 0) / 60;
}

export function timeToKill(weapon, damageMultiplier = 1) {
  const shots = Math.ceil(100 / (weapon.damage * damageMultiplier));
  return ((shots - 1) / shotsPerSecond(weapon)).toFixed(2);
}
